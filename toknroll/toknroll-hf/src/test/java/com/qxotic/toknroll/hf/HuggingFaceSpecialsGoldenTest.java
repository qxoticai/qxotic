package com.qxotic.toknroll.hf;

import static org.junit.jupiter.api.Assertions.fail;

import com.qxotic.format.json.Json;
import com.qxotic.toknroll.Specials;
import com.qxotic.toknroll.Tokenizer;
import com.qxotic.toknroll.testkit.GitRepoPaths;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.List;
import java.util.Map;
import java.util.function.Predicate;
import java.util.stream.Stream;
import org.junit.jupiter.api.Assumptions;
import org.junit.jupiter.api.DynamicTest;
import org.junit.jupiter.api.Tag;
import org.junit.jupiter.api.TestFactory;

/**
 * Special tokens, as Hugging Face matches them: {@code Specials.of(tokenizer).encode} gives the ids
 * {@code tokenizers} gives for text full of each model's added tokens. The goldens are generated by
 * {@code toknroll-benchmarks/generate_specials_golden.py}, one per supported model, pinned to a
 * commit. Every difference fails; a diagnosed one names its cause.
 */
@Tag("local-external")
class HuggingFaceSpecialsGoldenTest {

    private static final Path GOLDENS =
            GitRepoPaths.findGitRoot().resolve("test-fixtures/golden/specials");

    /** A diagnosed divergence: the texts it explains, and why. */
    private record Known(Predicate<String> explains, String cause) {}

    private static final Map<String, Known> KNOWN =
            Map.of(
                    "unsloth/gemma-3-4b-it",
                    new Known(
                            text -> text.contains("▁▁"),
                            "Gemma 3 declares 30 added tokens spelled as runs of ▁; toknroll"
                                    + " matches a special by its decoded text, spaces, as llama.cpp"
                                    + " does, so a literal ▁ run in the input is not one"));

    @TestFactory
    Stream<DynamicTest> specialsEncodeAsHuggingFace() throws IOException {
        Assumptions.assumeTrue(
                Files.isDirectory(GOLDENS),
                "no goldens in "
                        + GOLDENS
                        + ": run toknroll-benchmarks/generate_specials_golden.py");
        List<Path> goldens;
        try (Stream<Path> files = Files.list(GOLDENS)) {
            goldens = files.filter(p -> p.toString().endsWith(".json")).sorted().toList();
        }
        return goldens.stream()
                .map(
                        golden ->
                                DynamicTest.dynamicTest(
                                        golden.getFileName().toString(), () -> check(golden)));
    }

    @SuppressWarnings("unchecked")
    private static void check(Path golden) throws IOException {
        Map<String, Object> root =
                (Map<String, Object>) Json.parse(Files.readString(golden, StandardCharsets.UTF_8));
        String model = (String) root.get("model");
        String[] repo = model.split("/", 2);
        Tokenizer tokenizer =
                HuggingFaceTokenizerLoader.fromHuggingFace(
                        repo[0], repo[1], (String) root.get("revision"), false, false);
        Specials specials = Specials.of(tokenizer);

        List<Object> cases = (List<Object>) root.get("cases");
        Known known = KNOWN.get(model);
        List<String> unexplained = new ArrayList<>();
        int explained = 0;
        for (Object c : cases) {
            Map<String, Object> entry = (Map<String, Object>) c;
            String text = (String) entry.get("text");
            int[] want =
                    ((List<Object>) entry.get("ids"))
                            .stream().mapToInt(id -> ((Number) id).intValue()).toArray();
            int[] got = specials.encode(tokenizer, text).toArray();
            if (Arrays.equals(want, got)) continue;
            if (known != null && known.explains().test(text)) {
                explained++;
            } else {
                unexplained.add(
                        "'"
                                + text.replace("\n", "\\n")
                                + "'\n    hf   "
                                + Arrays.toString(want)
                                + "\n    ours "
                                + Arrays.toString(got));
            }
        }
        if (unexplained.isEmpty() && explained == 0) return;
        StringBuilder message =
                new StringBuilder(model)
                        .append(": ")
                        .append(unexplained.size() + explained)
                        .append(" of ")
                        .append(cases.size())
                        .append(" texts differ from Hugging Face");
        if (explained > 0) {
            message.append("; ")
                    .append(explained)
                    .append(" known divergence: ")
                    .append(known.cause());
        }
        unexplained.stream().limit(5).forEach(d -> message.append("\n  ").append(d));
        fail(message.toString());
    }
}
