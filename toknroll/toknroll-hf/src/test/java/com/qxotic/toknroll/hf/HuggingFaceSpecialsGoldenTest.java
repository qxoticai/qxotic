package com.qxotic.toknroll.hf;

import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.junit.jupiter.api.Assertions.fail;

import com.qxotic.format.json.Json;
import com.qxotic.toknroll.Specials;
import com.qxotic.toknroll.Tokenizer;
import java.io.IOException;
import java.net.URISyntaxException;
import java.net.URL;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.List;
import java.util.Map;
import java.util.stream.Stream;
import org.junit.jupiter.api.DynamicTest;
import org.junit.jupiter.api.Tag;
import org.junit.jupiter.api.TestFactory;

/**
 * Special tokens, as Hugging Face matches them: {@code Specials.of(tokenizer).encode} gives the ids
 * {@code tokenizers} gives for text full of each model's added tokens. The goldens, under the test
 * resources' {@code specials/} and not committed, are generated by {@code
 * toknroll-benchmarks/generate_specials_golden.py}, one per supported model, pinned to a commit.
 * Every difference fails.
 */
@Tag("local-external")
@Tag("network")
class HuggingFaceSpecialsGoldenTest {

    @TestFactory
    Stream<DynamicTest> specialsEncodeAsHuggingFace() throws IOException, URISyntaxException {
        URL resource = HuggingFaceSpecialsGoldenTest.class.getResource("/specials");
        assertNotNull(
                resource,
                "no specials goldens on the test classpath: run"
                        + " toknroll-benchmarks/generate_specials_golden.py");
        List<Path> goldens;
        try (Stream<Path> files = Files.list(Path.of(resource.toURI()))) {
            goldens = files.filter(p -> p.toString().endsWith(".json")).sorted().toList();
        }
        return goldens.stream()
                .map(
                        golden ->
                                DynamicTest.dynamicTest(
                                        golden.getFileName().toString(), () -> check(golden)));
    }

    @SuppressWarnings("unchecked")
    private static void check(Path golden) throws IOException {
        Map<String, Object> root =
                (Map<String, Object>) Json.parse(Files.readString(golden, StandardCharsets.UTF_8));
        String model = (String) root.get("model");
        String[] repo = model.split("/", 2);
        Tokenizer tokenizer =
                HuggingFaceTokenizerLoader.fromHuggingFace(
                        repo[0], repo[1], (String) root.get("revision"), false, false);
        Specials specials = Specials.of(tokenizer);

        List<Object> cases = (List<Object>) root.get("cases");
        List<String> differing = new ArrayList<>();
        for (Object c : cases) {
            Map<String, Object> entry = (Map<String, Object>) c;
            String text = (String) entry.get("text");
            int[] want =
                    ((List<Object>) entry.get("ids"))
                            .stream().mapToInt(id -> ((Number) id).intValue()).toArray();
            int[] got = specials.encode(tokenizer, text).toArray();
            if (!Arrays.equals(want, got)) {
                differing.add(
                        "'"
                                + text.replace("\n", "\\n")
                                + "'\n    hf   "
                                + Arrays.toString(want)
                                + "\n    ours "
                                + Arrays.toString(got));
            }
        }
        if (differing.isEmpty()) return;
        StringBuilder message =
                new StringBuilder(model)
                        .append(": ")
                        .append(differing.size())
                        .append(" of ")
                        .append(cases.size())
                        .append(" texts differ from Hugging Face");
        differing.stream().limit(5).forEach(d -> message.append("\n  ").append(d));
        fail(message.toString());
    }
}
