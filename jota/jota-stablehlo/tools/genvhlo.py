"""Generates vhlo/VhloOpSchemas.java from stablehlo/dialect/VhloOps.td.

Usage (from jota/):
  python3 jota-stablehlo/tools/genvhlo.py /path/to/openxla/stablehlo \
      jota-stablehlo/src/main/java/com/qxotic/jota/stablehlo/vhlo/VhloOpSchemas.java
  mvn -pl jota-stablehlo spotless:apply

Per VHLO op: its version window and its attribute names sorted by name, which is the order in
which ODS-generated readProperties() encodes them (all VHLO attributes are required).
"""
import re
import sys

repo, out = sys.argv[1], sys.argv[2]
td = open(f"{repo}/stablehlo/dialect/VhloOps.td").read()
ops = []
for m in re.finditer(r'def (VHLO_\w+)\s*:\s*VHLO_Op<"([\w-]+)",\s*"([\d.]+)",\s*"([\w.]+)"', td):
    start = m.end()
    nxt = td.find("\ndef ", start)
    body = td[start : nxt if nxt > 0 else len(td)]
    args = re.search(r"let arguments = \(\s*ins(.*?)\);", body, re.S)
    attrs = []
    if args:
        for a in re.finditer(r"(\w+(?:<[^>]*>)?)\s*:\s*\$(\w+)", args.group(1)):
            if "Attr" in a.group(1):
                attrs.append(a.group(2))
    ops.append((m.group(2), m.group(3), m.group(4), sorted(attrs)))

lines = []
for name, lo, hi, attrs in ops:
    names = ", ".join(f'"{a}"' for a in attrs)
    lines.append(f'        put("{name}", "{lo}", "{hi}"{", " + names if names else ""});')

src = f'''package com.qxotic.jota.stablehlo.vhlo;

import java.util.HashMap;
import java.util.List;
import java.util.Map;

/**
 * VHLO operation schemas, generated by {{@code tools/genvhlo.py}} from {{@code
 * stablehlo/dialect/VhloOps.td}} ({len(ops)} ops). Do not edit by hand.
 *
 * <p>The attribute names are sorted by name: ODS-generated {{@code readProperties}} encodes the
 * attributes of an op in that order, one attribute reference each (VHLO attributes are all
 * required).
 */
public final class VhloOpSchemas {{

    /** One versioned VHLO op ({{@code add_v1}}), valid from {{@code minVersion}} to {{@code maxVersion}}. */
    public record Schema(String mnemonic, String minVersion, String maxVersion, List<String> attributes) {{}}

    private static final Map<String, Schema> SCHEMAS = new HashMap<>();

    private VhloOpSchemas() {{}}

    private static void put(String mnemonic, String min, String max, String... attributes) {{
        SCHEMAS.put(mnemonic, new Schema(mnemonic, min, max, List.of(attributes)));
    }}

    /** Schema of {{@code vhlo.<mnemonic>}} (e.g. {{@code "gather_v2"}}), or null. */
    public static Schema get(String mnemonic) {{
        return SCHEMAS.get(mnemonic);
    }}

    public static int size() {{
        return SCHEMAS.size();
    }}

    static {{
{chr(10).join(lines)}
    }}
}}
'''
open(out, "w").write(src)
print(len(ops), "VHLO op schemas")
